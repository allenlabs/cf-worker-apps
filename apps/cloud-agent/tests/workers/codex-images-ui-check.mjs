import assert from "node:assert/strict";
import { Script } from "node:vm";
import { adminPage } from "../../workers/pi/admin-view.js";

const html = await adminPage({ PRODUCT_NAME: "Fixture Cloud Agent" }, true).text();
const script = html.match(/<script nonce="[^"]+">([\s\S]*)<\/script>/)[1];
new Script(script);
const calls = [], ui = { confirm: () => true }, results = new Map();
let refreshes = 0;
ui.api = async (path, body) => { calls.push({ path, body }); return results.get(path) ?? {}; };
ui.refresh = async () => { refreshes++; };
new Script(script.slice(script.indexOf("const esc="), script.indexOf("async function api(")) + script.slice(script.indexOf("const imageAttempts="), script.indexOf("async function refresh(")) + "globalThis.attempts=imageAttempts;").runInNewContext(ui);
const account = { id: "fixture-account", label: "Fixture account" };
const data = { accountSelection: { mode: "fixed", poolAccountIds: [] } };
assert.match(ui.accountView(account, data), /이미지 로그인 시작/);
assert.match(ui.imageAccountView({ ...account, image: { loginFailed: true } }), /로그인에 실패했습니다/);
results.set("/api/images/start", { verificationUrl: "https://auth.openai.com/codex/device", userCode: "FIXTURE-CODE<unsafe>", expiresAt: "2026-10-06T00:00:00Z" });
await ui.imageAccountAction("image-start", account.id);
assert.equal(calls[0].path, "/api/images/start"); assert.deepEqual(JSON.parse(JSON.stringify(calls[0].body)), { id: account.id });
const pendingCard = ui.imageAccountView({ ...account, image: { loginPending: true } });
assert.match(pendingCard, /FIXTURE-CODE&lt;unsafe&gt;/);
assert.match(pendingCard, /href="https:\/\/auth.openai.com\/codex\/device"/);
assert.match(pendingCard, /rel="noopener noreferrer"/);
assert.match(pendingCard, /로그인 완료 확인/);
assert.equal(calls.length, 1, "opening the code card never polls or signs in automatically");
const reconnectCard = ui.imageAccountView({ ...account, image: { connected: true, loginPending: true, identity: { accountId: "previous-account", planType: "pro" } } });
assert.match(reconnectCard, /FIXTURE-CODE&lt;unsafe&gt;/); assert.match(reconnectCard, /로그인 완료 확인/); assert.equal(ui.attempts.size, 1);
results.set("/api/images/check", { pending: true });
await ui.imageAccountAction("image-check", account.id);
assert.equal(calls[1].path, "/api/images/check"); assert.equal(ui.attempts.size, 1);
results.set("/api/images/check", { connected: true });
await ui.imageAccountAction("image-check", account.id); assert.equal(ui.attempts.size, 0);
assert.match(ui.imageAccountView({ ...account, image: { connected: true, identity: { accountId: "selected<account>", planType: "pro" } } }), /selected&lt;account&gt;/);
ui.confirm = () => false;
const beforeCancelled = calls.length;
await ui.imageAccountAction("image-disconnect", account.id); assert.equal(calls.length, beforeCancelled);
ui.confirm = () => true;
await ui.imageAccountAction("image-disconnect", account.id);
assert.equal(calls.at(-1).path, "/api/images/disconnect"); assert.deepEqual(JSON.parse(JSON.stringify(calls.at(-1).body)), { id: account.id, confirmed: true });
results.set("/api/images/start", { verificationUrl: "https://evil.invalid", userCode: "FIXTURE" });
await assert.rejects(ui.imageAccountAction("image-start", account.id), /응답을 확인/); assert.equal(ui.attempts.size, 0);
assert.equal(refreshes, 4);
console.log("Codex image UI checks passed: account-scoped routes, escaped user code, official link, manual confirmation, confirmed disconnect; no automatic polling.");

import { lstat, mkdir, realpath, rename } from 'node:fs/promises';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { MAX_ARTIFACT_BYTES, canonicalSource, check, hash, immutableFile, installationId, parseArtifact, parseJson, readBounded, validDigest } from './plugin-artifacts.mjs';

const GENERATED = '// Generated by apply-host-plugin-inventory.mjs.';
const PLACEHOLDER = '// Cloud Agent OS installed plugin registry placeholder.';
function exact(value, keys) {
  check(value && typeof value === 'object' && !Array.isArray(value) && Object.keys(value).length === keys.length && keys.every(key => Object.hasOwn(value, key)), 'PLUGIN_HOST_MANIFEST_INVALID');
}
export function parseHostManifest(value) {
  exact(value, ['apiVersion', 'desired', 'deployment', 'installations', 'artifacts']);
  exact(value.desired, ['revision', 'digest']);
  exact(value.deployment, ['sourceRoot', 'sourceRevision', 'configPath', 'configDigest']);
  check(value.apiVersion === 1 && Number.isSafeInteger(value.desired.revision) && value.desired.revision >= 0, 'PLUGIN_HOST_MANIFEST_INVALID');
  validDigest(value.desired.digest); validDigest(value.deployment.configDigest);
  check(isAbsolute(value.deployment.sourceRoot) && isAbsolute(value.deployment.configPath) && /^[a-f0-9]{40}$/.test(value.deployment.sourceRevision), 'PLUGIN_HOST_MANIFEST_INVALID');
  check(Array.isArray(value.installations) && value.installations.length <= 500 && Array.isArray(value.artifacts) && value.artifacts.length <= 500, 'PLUGIN_HOST_MANIFEST_INVALID');
  const ids = new Set(), digests = new Set();
  for (const artifact of value.artifacts) {
    exact(artifact, ['digest', 'file']); validDigest(artifact.digest);
    check(typeof artifact.file === 'string' && isAbsolute(artifact.file) && !digests.has(artifact.digest), 'PLUGIN_HOST_MANIFEST_INVALID'); digests.add(artifact.digest);
  }
  for (const job of value.installations) {
    exact(job, ['id', 'resourceId', 'source', 'execution', 'artifactDigest']);
    check(typeof job.resourceId === 'string' && /^[a-zA-Z0-9][a-zA-Z0-9._:-]{0,127}$/.test(job.resourceId) && job.execution === 'host' && !ids.has(job.id), 'PLUGIN_HOST_MANIFEST_INVALID');
    canonicalSource(job.source); validDigest(job.id); validDigest(job.artifactDigest);
    check(installationId({ id: job.resourceId, source: job.source, execution: job.execution }) === job.id && digests.has(job.artifactDigest), 'PLUGIN_HOST_MANIFEST_INVALID'); ids.add(job.id);
  }
  check(digests.size === new Set(value.installations.map(value => value.artifactDigest)).size, 'PLUGIN_HOST_MANIFEST_INVALID');
  return value;
}
/** Only a prepared disposable checkout is modified. The caller retains all deploy guards. */
export async function applyHostInventory({ manifestFile, checkout }) {
  checkout = resolve(checkout);
  check(await realpath(checkout) === checkout, 'PLUGIN_HOST_CHECKOUT_INVALID');
  const prepared = parseJson(await readBounded(join(dirname(checkout), 'prepared.json'), 4096));
  exact(prepared, ['upstream', 'overlayHash']);
  check(/^[a-f0-9]{40}$/.test(prepared.upstream) && /^[a-f0-9]{64}$/.test(prepared.overlayHash), 'PLUGIN_HOST_CHECKOUT_NOT_PREPARED');
  const bytes = await readBounded(manifestFile, MAX_ARTIFACT_BYTES);
  const manifest = parseHostManifest(parseJson(bytes));
  check(checkout !== resolve(manifest.deployment.sourceRoot), 'PLUGIN_HOST_CHECKOUT_INVALID');
  const src = join(checkout, 'packages/workshop-backend/src');
  check(await realpath(src) === src, 'PLUGIN_HOST_CHECKOUT_INVALID');
  const registry = join(src, 'installed-agent-plugins.ts');
  const existing = (await readBounded(registry, MAX_ARTIFACT_BYTES)).toString('utf8');
  check(existing.startsWith(PLACEHOLDER + '\n') || existing.startsWith(GENERATED + '\n'), 'PLUGIN_HOST_REGISTRY_UNRECOGNIZED');
  const modules = join(src, 'installed-agent-plugin-modules');
  await mkdir(modules, { recursive: true, mode: 0o700 });
  const info = await lstat(modules);
  check(info.isDirectory() && !info.isSymbolicLink() && await realpath(modules) === modules, 'PLUGIN_HOST_CHECKOUT_INVALID');
  const entries = [];
  for (const item of [...manifest.artifacts].sort((a, b) => a.digest.localeCompare(b.digest))) {
    const artifactBytes = await readBounded(item.file, MAX_ARTIFACT_BYTES);
    check(hash(artifactBytes) === item.digest, 'PLUGIN_ARTIFACT_DIGEST_MISMATCH');
    const artifact = parseArtifact(parseJson(artifactBytes));
    for (const job of manifest.installations.filter(value => value.artifactDigest === item.digest)) check(JSON.stringify(canonicalSource(artifact.source)) === JSON.stringify(canonicalSource(job.source)), 'PLUGIN_ARTIFACT_SOURCE_MISMATCH');
    const target = join(modules, `${item.digest}.mjs`);
    await immutableFile(target, Buffer.from(artifact.module));
    await immutableFile(join(modules, `${item.digest}.d.mts`), 'declare const plugin: unknown;\nexport default plugin;\nexport declare const Plugin: unknown;\n');
    entries.push(`  ${JSON.stringify(item.digest)}: () => import(${JSON.stringify(`./installed-agent-plugin-modules/${item.digest}.mjs`)}),`);
  }
  const next = `${GENERATED}\n// Modules are evaluated only after the runtime verifies a current authorized installation.\nexport const installedAgentPlugins: Readonly<Record<string, () => Promise<unknown>>> = {\n${entries.join('\n')}\n};\n`;
  const temporary = `${registry}.${hash(next)}.tmp`;
  await immutableFile(temporary, next);
  await rename(temporary, registry);
  return { ok: true, manifestDigest: hash(bytes), artifacts: entries.length };
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const { values } = parseArgs({ options: { manifest: { type: 'string' }, checkout: { type: 'string' } } });
    check(values.manifest && values.checkout, 'PLUGIN_HOST_ARGUMENTS_REQUIRED');
    process.stdout.write(JSON.stringify(await applyHostInventory({ manifestFile: resolve(values.manifest), checkout: resolve(values.checkout) })) + '\n');
  } catch (error) {
    process.stderr.write((typeof error.message === 'string' && /^PLUGIN_[A-Z_]+$/.test(error.message) ? error.message : 'PLUGIN_HOST_INVENTORY_FAILED') + '\n');
    process.exitCode = 1;
  }
}
